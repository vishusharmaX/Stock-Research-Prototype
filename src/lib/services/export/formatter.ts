import { ResearchRun, ResearchReport, ResearchEvent, ResearchSource, ResearchMetrics } from "../../types/research";

export interface FullTranscriptPayload {
  run: ResearchRun;
  report?: ResearchReport;
  metrics?: ResearchMetrics;
  events: ResearchEvent[];
  sources: ResearchSource[];
  exportedAt: string;
  disclaimer: string;
}

export function formatTranscriptJson(data: {
  run: ResearchRun;
  report?: ResearchReport;
  metrics?: ResearchMetrics;
  events: ResearchEvent[];
  sources: ResearchSource[];
}): string {
  const payload: FullTranscriptPayload = {
    run: data.run,
    report: data.report,
    metrics: data.metrics,
    events: data.events,
    sources: data.sources,
    exportedAt: new Date().toISOString(),
    disclaimer:
      "This transcript and report are generated by Equity Intelligence for decision-support and institutional research purposes. Not financial advice.",
  };

  return JSON.stringify(payload, null, 2);
}

export function formatTranscriptMarkdown(data: {
  run: ResearchRun;
  report?: ResearchReport;
  metrics?: ResearchMetrics;
  events: ResearchEvent[];
  sources: ResearchSource[];
}): string {
  const lines: string[] = [];

  // Title & Header
  lines.push(`# Equity Intelligence — Institutional Research Report`);
  lines.push(`**Research Run ID:** \`${data.run.id}\``);
  lines.push(`**Date Generated:** ${data.report?.header.generatedAt || data.run.createdAt}`);
  lines.push(`**Target Asset:** ${data.report?.header.companyName || data.run.companyName || "N/A"} (${data.report?.header.ticker || data.run.normalizedTicker || "N/A"})`);
  lines.push(`**Research Question:** ${data.run.question}`);
  lines.push(`**Execution Status:** ${data.run.status.toUpperCase()}`);
  lines.push(``);
  lines.push(`---`);
  lines.push(``);

  if (data.report) {
    const rep = data.report;

    // Executive Summary
    lines.push(`## 1. Executive Summary`);
    lines.push(rep.executiveSummary);
    lines.push(``);

    // Key Findings
    lines.push(`## 2. Key Investment Findings`);
    for (const finding of rep.keyFindings) {
      const citations = finding.citationIndices.map((i) => `[[${i}]]`).join(" ");
      lines.push(`### ${finding.title} ${citations}`);
      lines.push(`${finding.explanation}`);
      lines.push(`> **Financial Evidence:** ${finding.financialEvidence}`);
      lines.push(``);
    }

    // Financial Snapshot Table
    lines.push(`## 3. Financial Performance Snapshot`);
    lines.push(`| Metric | Reported Value | Period | Currency | Citation |`);
    lines.push(`| :--- | :--- | :--- | :--- | :--- |`);
    for (const m of rep.financialSnapshot) {
      const citation = m.citationIndex ? `[[${m.citationIndex}]]` : "N/A";
      const val = m.isUnavailable ? "_Unavailable_" : m.value;
      lines.push(`| ${m.metric} | **${val}** | ${m.period} | ${m.currency} | ${citation} |`);
    }
    lines.push(``);

    // Bull vs Bear
    lines.push(`## 4. Investment Thesis: Bull vs. Bear Case`);
    lines.push(`### Bull Case (Upside Drivers)`);
    for (const d of rep.bullCase.growthDrivers) lines.push(`- **Driver:** ${d}`);
    for (const a of rep.bullCase.competitiveAdvantages) lines.push(`- **Moat:** ${a}`);
    for (const c of rep.bullCase.potentialCatalysts) lines.push(`- **Catalyst:** ${c}`);
    lines.push(`\n**Supporting Evidence:** ${rep.bullCase.supportingEvidence}\n`);

    lines.push(`### Bear Case (Material Risks)`);
    for (const r of rep.bearCase.executionRisks) lines.push(`- **Execution Risk:** ${r}`);
    for (const v of rep.bearCase.valuationRisks) lines.push(`- **Valuation Risk:** ${v}`);
    for (const t of rep.bearCase.competitiveThreats) lines.push(`- **Competitive Threat:** ${t}`);
    lines.push(`\n**Counter-Evidence:** ${rep.bearCase.invalidatingEvidence}\n`);

    // Valuation Analysis
    lines.push(`## 5. Valuation Multiple Analysis`);
    lines.push(`| Multiple | Current Value | Peer Average | Historical Average | Interpretation |`);
    lines.push(`| :--- | :--- | :--- | :--- | :--- |`);
    for (const v of rep.valuation.multiples) {
      lines.push(
        `| ${v.name} | **${v.currentValue}** | ${v.peerAverage || "N/A"} | ${v.historicalAverage || "N/A"} | ${v.interpretation} |`
      );
    }
    lines.push(``);
    lines.push(`**Key Valuation Assumptions:**`);
    for (const a of rep.valuation.keyAssumptions) lines.push(`- ${a}`);
    if (rep.valuation.sensitivitySummary) {
      lines.push(`\n*Sensitivity Summary:* ${rep.valuation.sensitivitySummary}`);
    }
    lines.push(``);

    // Catalysts & Risks
    lines.push(`## 6. Catalysts and Monitoring Indicators`);
    for (const item of rep.catalystsAndRisks) {
      lines.push(`- **[${item.type.toUpperCase()}] ${item.title}** (${item.impact.toUpperCase()} impact, ${item.timeframe}): ${item.explanation}`);
      lines.push(`  *Monitoring Metric:* ${item.monitoringIndicators}`);
    }
    lines.push(``);

    // Conclusion
    lines.push(`## 7. Synthesis and Analytical Conclusion`);
    lines.push(`**Thesis Recap:** ${rep.conclusion.thesisRecap}`);
    lines.push(``);
    lines.push(`**Principal Thesis Vulnerability:** ${rep.conclusion.principalVulnerability}`);
    lines.push(``);
    lines.push(`**Key Indicators to Watch:**`);
    for (const k of rep.conclusion.monitoringChecklist) lines.push(`- [ ] ${k}`);
    lines.push(``);
    lines.push(`*Confidence Level:* **${rep.conclusion.confidenceAssessment.level.toUpperCase()}** — ${rep.conclusion.confidenceAssessment.basis}`);
    lines.push(``);

    // Sources & Citations
    lines.push(`## 8. Verifiable Primary Sources & Citations`);
    for (const s of data.sources) {
      if (!s.isRetained) continue;
      lines.push(`[${s.citationIndex}] [${s.title}](${s.url})`);
      lines.push(`    *Source:* ${s.domain} | *Accessed:* ${s.accessDate} ${s.publishDate ? `| *Published:* ${s.publishDate}` : ""}`);
      lines.push(`    > "${s.excerpt}"`);
      lines.push(``);
    }

    lines.push(`---`);
    lines.push(`### Regulatory Disclaimer`);
    lines.push(rep.disclaimer);
    lines.push(``);
  }

  // Observability & Transcript Log
  lines.push(`---`);
  lines.push(`## 9. Agent Execution Transcript & Token Telemetry`);
  if (data.metrics) {
    const m = data.metrics;
    lines.push(`### Token & Efficiency Metrics`);
    lines.push(`- **Provider:** \`${m.provider}\` (Model: \`${m.model}\`)`);
    lines.push(`- **Latency:** ${(m.durationMs / 1000).toFixed(2)} seconds`);
    lines.push(`- **Input Tokens:** ${m.inputTokens !== null ? m.inputTokens.toLocaleString() : "Not reported by provider"}`);
    lines.push(`- **Output Tokens:** ${m.outputTokens !== null ? m.outputTokens.toLocaleString() : "Not reported by provider"}`);
    lines.push(`- **Total Tokens:** ${m.totalTokens !== null ? m.totalTokens.toLocaleString() : "Not reported by provider"}`);
    lines.push(`- **Sources Discovered vs Retained:** ${m.sourcesDiscovered} discovered, ${m.sourcesRetained} retained (${m.deduplicatedCount} deduplicated)`);
    lines.push(`- **Estimated Cost:** ${m.estimatedCostUsd !== null ? `$${m.estimatedCostUsd.toFixed(4)}` : "N/A"} (${m.pricingNotes})`);
    lines.push(``);
  }

  lines.push(`### Chronological Agent Event Log`);
  lines.push(`| Step | Phase | Event | Timestamp | Message |`);
  lines.push(`| :--- | :--- | :--- | :--- | :--- |`);
  for (const ev of data.events) {
    const time = ev.timestamp.replace("T", " ").replace("Z", "");
    lines.push(`| ${ev.stepNumber} | \`${ev.phase}\` | \`${ev.type}\` | ${time} | ${ev.message} |`);
  }

  return lines.join("\n");
}
